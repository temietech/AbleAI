import React, { useState, useRef, useEffect } from 'react';
import { Bot, Send, X, Sparkles, CheckCircle2, ArrowRight, ShieldCheck, RefreshCw } from 'lucide-react';
import { sendCopilotChat } from '../services/api.js';

export default function AgentCopilotDrawer({
  isOpen,
  onClose,
  financialContext,
  onTriggerAction
}) {
  const [messages, setMessages] = useState([
    {
      id: 'm1',
      sender: 'agent',
      text: "Hi Alex! I'm your Able AI Agent. I continuously analyze your spending velocity and safe-spend limits. How can I help you optimize your cash flow today?",
      action: null,
      timestamp: 'Just now'
    }
  ]);
  const [inputText, setInputText] = useState('');
  const [isLoading, setIsLoading] = useState(false);
  const messagesEndRef = useRef(null);

  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [messages]);

  const quickQuestions = [
    "Can I afford dinner tonight for £25?",
    "Sweep £20 to my Emergency Buffer",
    "How's my Ibiza trip pool progressing?"
  ];

  const handleSendMessage = async (textToSend) => {
    const text = textToSend || inputText;
    if (!text || !text.trim() || isLoading) return;

    const userMsg = {
      id: `u-${Date.now()}`,
      sender: 'user',
      text: text.trim(),
      timestamp: 'Now'
    };

    setMessages((prev) => [...prev, userMsg]);
    setInputText('');
    setIsLoading(true);

    try {
      const response = await sendCopilotChat(text.trim(), messages, financialContext);
      const agentMsg = {
        id: `a-${Date.now()}`,
        sender: 'agent',
        text: response.reply,
        action: response.action,
        timestamp: 'Just now'
      };
      setMessages((prev) => [...prev, agentMsg]);
    } catch (err) {
      setMessages((prev) => [
        ...prev,
        {
          id: `a-${Date.now()}`,
          sender: 'agent',
          text: "I'm having a little trouble connecting to my Gemini brain, but your current daily safe spend limit is £34.50. You're tracking comfortably!",
          timestamp: 'Just now'
        }
      ]);
    } finally {
      setIsLoading(false);
    }
  };

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex justify-end bg-[#0A1628]/60 backdrop-blur-xs animate-in fade-in duration-200">
      <div className="w-full max-w-md bg-white h-full shadow-2xl flex flex-col border-l border-slate-200 animate-in slide-in-from-right duration-300">
        {/* Header */}
        <div className="p-5 bg-[#0A1628] text-white flex items-center justify-between border-b border-slate-800">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-gradient-to-tr from-teal-500 to-blue-600 flex items-center justify-center text-white shadow-md">
              <Bot className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="font-extrabold text-base text-white">Able AI Copilot</h3>
                <span className="text-[10px] font-bold px-2 py-0.5 rounded-full bg-teal-500/20 text-teal-300 border border-teal-500/30">
                  Agentic Commerce
                </span>
              </div>
              <p className="text-xs text-slate-400">Autonomous Financial Intelligence</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 rounded-xl text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Live Context Bar */}
        <div className="px-5 py-2.5 bg-slate-50 border-b border-slate-200 text-xs font-semibold text-slate-600 flex items-center justify-between">
          <span>Safe-Spend: <strong className="text-[#0A1628]">£{financialContext.dailySafeSpend?.toFixed(2)}/day</strong></span>
          <span>Balance: <strong className="text-teal-700">£{financialContext.lumpBalance?.toFixed(2)}</strong></span>
        </div>

        {/* Messages Stream */}
        <div className="flex-1 overflow-y-auto p-5 space-y-4">
          {messages.map((m) => (
            <div
              key={m.id}
              className={`flex flex-col ${m.sender === 'user' ? 'items-end' : 'items-start'}`}
            >
              <div
                className={`max-w-[85%] rounded-2xl px-4 py-3 text-sm leading-relaxed shadow-xs ${
                  m.sender === 'user'
                    ? 'bg-blue-600 text-white rounded-br-xs font-medium'
                    : 'bg-slate-100 text-[#0A1628] rounded-bl-xs'
                }`}
              >
                {m.text}
              </div>

              {/* Action Directive Card if generated by Agent */}
              {m.action && (
                <div className="mt-2.5 max-w-[85%] bg-gradient-to-br from-teal-50 to-blue-50 border border-teal-200 rounded-2xl p-3.5 space-y-2.5 shadow-sm">
                  <div className="flex items-center justify-between text-xs">
                    <span className="font-extrabold text-teal-900 flex items-center gap-1.5">
                      <Sparkles className="w-3.5 h-3.5 text-teal-600" />
                      Agent Proposed PayPal Action
                    </span>
                    <span className="font-mono font-bold text-teal-800">
                      £{Number(m.action.amount).toFixed(2)}
                    </span>
                  </div>
                  <p className="text-xs text-slate-600">
                    Route micro-surplus into <strong>{m.action.targetName}</strong> via PayPal Sandbox.
                  </p>
                  <button
                    onClick={() => onTriggerAction(m.action)}
                    className="w-full py-2.5 px-3 rounded-xl bg-[#FFC439] hover:bg-[#F4BB33] text-[#003087] font-extrabold text-xs shadow-xs flex items-center justify-center gap-1.5 transition-all"
                  >
                    <span className="italic font-black text-sm">
                      Pay<span className="text-[#0079C1]">Pal</span>
                    </span>
                    <span>• Execute £{Number(m.action.amount).toFixed(2)} Sweep</span>
                  </button>
                </div>
              )}

              <span className="text-[10px] text-slate-400 mt-1 px-1">
                {m.timestamp}
              </span>
            </div>
          ))}

          {isLoading && (
            <div className="flex items-center gap-2 text-xs text-slate-500 bg-slate-50 p-3 rounded-2xl max-w-[70%]">
              <RefreshCw className="w-3.5 h-3.5 animate-spin text-teal-600" />
              <span>Gemini Agent is calculating velocity...</span>
            </div>
          )}
          <div ref={messagesEndRef} />
        </div>

        {/* Quick Suggestion Pills */}
        <div className="px-5 py-2.5 bg-slate-50/80 border-t border-slate-200 overflow-x-auto flex gap-2">
          {quickQuestions.map((q, idx) => (
            <button
              key={idx}
              onClick={() => handleSendMessage(q)}
              className="text-[11px] font-semibold text-slate-600 bg-white border border-slate-200 px-3 py-1.5 rounded-full hover:bg-teal-50 hover:border-teal-300 hover:text-teal-800 shrink-0 transition-colors"
            >
              {q}
            </button>
          ))}
        </div>

        {/* Input Bar */}
        <div className="p-4 bg-white border-t border-slate-200">
          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleSendMessage();
            }}
            className="flex items-center gap-2"
          >
            <input
              type="text"
              placeholder="Ask Able AI about your spend or savings..."
              value={inputText}
              onChange={(e) => setInputText(e.target.value)}
              className="flex-1 px-4 py-3 rounded-xl border border-slate-200 text-xs font-semibold focus:outline-none focus:ring-2 focus:ring-teal-500 bg-slate-50/50"
            />
            <button
              type="submit"
              disabled={isLoading || !inputText.trim()}
              className="p-3 rounded-xl bg-[#0A1628] hover:bg-slate-800 text-white disabled:opacity-50 transition-colors"
            >
              <Send className="w-4 h-4 text-teal-400" />
            </button>
          </form>
        </div>
      </div>
    </div>
  );
}
